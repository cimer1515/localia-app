-- HARBOR / LOCALIA certificate persistence
-- Run in Supabase SQL Editor. Keep the certificates Storage bucket PRIVATE.
create extension if not exists pgcrypto;

create table if not exists public.issuer_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  active boolean not null default false,
  issuer_name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.certificates (
  certificate_id text primary key,
  credential_id text not null unique,
  owner_id uuid references auth.users(id) on delete set null,
  certificate_type text not null,
  issuer_name text not null,
  approved_at timestamptz not null,
  business_name text not null,
  activity text not null,
  city text not null,
  storage_bucket text not null default 'certificates',
  storage_path text not null,
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  tx_hash text not null,
  chain_id bigint not null,
  registry_address text not null,
  issuer_wallet text not null,
  status text not null check (status in ('confirmed','revoked','superseded')),
  verification_url text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.issuer_roles enable row level security;
alter table public.certificates enable row level security;

-- No public read policy: verification is performed through the server function
-- using the Supabase service role. Only authenticated owners may see their
-- own metadata; signed PDF access is still generated by the server.
drop policy if exists "certificate owner reads own metadata" on public.certificates;
create policy "certificate owner reads own metadata"
  on public.certificates for select to authenticated
  using (owner_id = auth.uid());

-- Do not grant client insert/update/delete. Service role is used only in Netlify
-- functions and bypasses RLS. Add reviewer accounts to issuer_roles manually
-- after verifying their identity.
grant select on public.certificates to authenticated;
revoke insert, update, delete on public.certificates from anon, authenticated;
revoke all on public.issuer_roles from anon, authenticated;

